class FakeClock:
    """Stand-in for the ``time`` module: only ``time()`` is used by wave.py."""

    def __init__(self, t0: float = 0.0):
        self.t = float(t0)

    def time(self) -> float:
        return self.t

    def set(self, t: float) -> None:
        self.t = float(t)

    def advance(self, dt: float) -> float:
        self.t += float(dt)
        return self.t


@contextmanager
def patched_clock(clock: FakeClock, modules: Sequence[object] = ()):
    """Rebind ``mod.time`` (not ``time.time``) so the fake clock is scoped to those
    modules only -- patching the stdlib ``time`` module would corrupt everything
    else in the process, including the recorder and pandas."""
    mods = list(modules) or [wave]
    saved = [(m, getattr(m, "time", None)) for m in mods]
    for m in mods:
        m.time = clock            # type: ignore[attr-index]
    try:
        yield clock
    finally:
        for m, old in saved:
            if old is not None:
                m.time = old      # type: ignore[attr-index]


