def book_asof(cap: Capture, symbol: str, venue: str, t: float) -> Book:
    """Top-of-book as of ``t`` (last message at or before ``t``)."""
    b = cap.books(symbol)
    ts = b["ts"]
    if not len(ts):
        return Book(venue, symbol)
    i = int(np.searchsorted(ts, t, side="right")) - 1
    if i < 0:
        i = 0
    bids = [(float(b["bid"][i]), float(b["bid_sz"][i]))] if b["bid"][i] > 0 else []
    asks = [(float(b["ask"][i]), float(b["ask_sz"][i]))] if b["ask"][i] > 0 else []
    return Book(venue, symbol, bids=bids, asks=asks, ts=t)


def basis_path(t: np.ndarray, signal_basis_bps: float, pulse_every_s: float,
               tau_s: float, noise_bps: float, seed: int = 0) -> np.ndarray:
    """Signed basis (Lighter rich = positive) as a train of decaying dislocations.

    The wave machine only acts when ``|basis| >= entry_bps`` and aborts when it
    reverts to ``exit_bps``, so an A/B on slicing needs repeated, realistic
    opportunities: a pulse, then mean reversion, then the next pulse.  Shape is
    synthetic by construction and is labelled as such everywhere downstream.
    """
    rng = np.random.default_rng(seed)
    out = np.zeros(len(t))
    if len(t) < 2:
        return out
    t0 = t[0]
    pulses = np.arange(t0, t[-1], max(pulse_every_s, tau_s / 4))
    for p in pulses:
        sign = 1.0 if rng.random() < 0.5 else -1.0
        amp = signal_basis_bps * (0.7 + 0.6 * rng.random())
        m = t >= p
        out[m] += sign * amp * np.exp(-(t[m] - p) / max(tau_s, 1e-6))
    out += rng.standard_normal(len(t)) * noise_bps
    return out


def okx_capture_from_basis(lt_cap: Capture, lt_symbol: str, basis_bps: np.ndarray,
                           grid_ts: np.ndarray, *, half_spread_bps: float = 1.0,
                           touch_size_base: float = 25.0, trade_intensity_per_s: float = 1.5,
                           trade_size_base: float = 2.0, cancel_intensity_per_s: float = 0.5,
                           seed: int = 5, step_s: float = 0.5) -> Capture:
    """Synthetic OKX leg: mid = Lighter mid / (1 + basis/1e4), plus generated flow."""
    b = lt_cap.books(lt_symbol)
    lt_mid = np.interp(grid_ts, b["ts"], b["mid"])
    okx_mid = lt_mid / (1.0 + basis_bps / 1e4)
    okx_mid = np.where(np.isfinite(okx_mid) & (okx_mid > 0), okx_mid, float(np.nanmedian(okx_mid)))
    return synthetic_capture(symbol=f"{lt_symbol}-OKX", duration_s=float(grid_ts[-1] - grid_ts[0]),
                             step_s=step_s, mid0=float(okx_mid[0]),
                             mid_path=(grid_ts, okx_mid), half_spread_bps=half_spread_bps,
                             touch_size_base=touch_size_base,
                             trade_intensity_per_s=trade_intensity_per_s,
                             trade_size_base=trade_size_base,
                             cancel_intensity_per_s=cancel_intensity_per_s,
                             seed=seed, order_poll_s=max(step_s, 1.0))


