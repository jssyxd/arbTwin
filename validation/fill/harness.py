class RestingOrderSim:
    """One resting post-only order, advanced along the recorded/synthetic stream.

    ``mode="queue"``      : FIFO queue ahead drains at the measured
                            ``mu_trade(d) + mu_cancel(d)``; a Bernoulli
                            ``pi(d) * dt`` fires the sweep-through event; and a
                            *recorded* strict move-through always fills.
    ``mode="price_through"``: only a recorded strict move-through fills -- the
                            ``RestingQuote.crossed`` baseline.
    """

    def __init__(self, cap: Capture, symbol: str, venue: str, side: str, px: float,
                 qty: float, t0: float, calib, rng: np.random.Generator, mode: str = "queue",
                 edges: Sequence[float] = DEFAULT_BUCKETS, queue_mult: float = 1.0,
                 use_cancel: bool = True, source: str = "captured"):
        self.cap, self.symbol, self.venue, self.side = cap, symbol, venue, side
        self.px, self.qty, self.t0, self.mode = float(px), float(qty), float(t0), mode
        self.calib, self.rng, self.edges = calib, rng, edges
        self.queue_mult, self.use_cancel, self.source = queue_mult, use_cancel, source
        b = cap.books(symbol)
        self._ts, self._bid, self._ask, self._mid = b["ts"], b["bid"], b["ask"], b["mid"]
        i = bucket_of(max(distance_bps(px, self._mid_at(t0), side), 0.0), edges)
        q = float(calib.queue_base[i]) if calib is not None else float("nan")
        if not np.isfinite(q) or q <= 0:
            q = float(np.nanmedian(np.asarray(calib.queue_base))) if calib is not None else 1.0
        self.queue0 = (q if np.isfinite(q) and q > 0 else 1.0) * queue_mult
        self.queue = self.queue0
        self.d0 = distance_bps(px, self._mid_at(t0), side)
        self.filled = False
        self.fill_ts = float("nan")
        self.fill_reason = ""
        self.n_requeues = 0
        self._i = max(0, int(np.searchsorted(self._ts, t0, side="right")) - 1)

    # -- internals -----------------------------------------------------------
    def _mid_at(self, t: float) -> float:
        if not len(self._ts):
            return float("nan")
        i = int(np.searchsorted(self._ts, t, side="right")) - 1
        return float(self._mid[max(i, 0)])

    def _rates(self, d: float) -> tuple[float, float, float]:
        if self.calib is None:
            return 0.0, 0.0, 0.0
        i = bucket_of(max(d, 0.0), self.edges)
        mu_tr = float(self.calib.trade_rate_base_per_s[i])
        mu_ca = float(self.calib.cancel_rate_base_per_s[i]) if self.use_cancel else 0.0
        pi = float(self.calib.through_hazard_per_s[i])
        return (0.0 if not np.isfinite(mu_tr) else mu_tr,
                0.0 if not np.isfinite(mu_ca) else mu_ca,
                0.0 if not np.isfinite(pi) else pi)

    def _crossed_between(self, t0: float, t1: float) -> Optional[float]:
        """Recorded strict move-through inside (t0, t1] -- a fact, not a model."""
        if not len(self._ts):
            return None
        i0 = int(np.searchsorted(self._ts, t0, side="right"))
        i1 = int(np.searchsorted(self._ts, t1, side="right"))
        if i1 <= i0:
            return None
        if self.side == "buy":
            hit = np.nonzero(self._ask[i0:i1] < self.px)[0]
        else:
            hit = np.nonzero(self._bid[i0:i1] > self.px)[0]
        return float(self._ts[i0 + hit[0]]) if len(hit) else None

    # -- api -----------------------------------------------------------------
    def step(self, t1: float) -> Optional[float]:
        """Advance to ``t1``; return the fill timestamp if we filled."""
        if self.filled or self.qty <= 0:
            return self.fill_ts if self.filled else None
        fact = self._crossed_between(self._last_t if hasattr(self, "_last_t") else self.t0, t1)
        if fact is not None:
            return self._fill(fact, "price_through_recorded")
        self._last_t = t1
        if self.mode != "queue":
            return None
        dt = max(0.0, t1 - (self._last_step_t if hasattr(self, "_last_step_t") else self.t0))
        self._last_step_t = t1
        if dt <= 0:
            return None
        d = distance_bps(self.px, self._mid_at(t1), self.side)
        if not np.isfinite(d):
            return None
        mu_tr, mu_ca, pi = self._rates(d)
        drawn = self.rng.poisson(max((mu_tr + mu_ca) * dt, 0.0))
        if drawn:
            self.queue -= float(drawn)
        if self.rng.random() < min(max(pi * dt, 0.0), 1.0):
            return self._fill(t1, "through_hazard")
        if self.queue <= 0:
            return self._fill(t1, "queue_depleted")
        return None

    def _fill(self, ts: float, reason: str) -> float:
        self.filled, self.fill_ts, self.fill_reason = True, float(ts), reason
        return self.fill_ts

    def requeue(self, px: float, t: float) -> None:
        """Cancel/replace: back of the queue at the new price."""
        self.px = float(px)
        self.t0 = t
        self._last_t = t
        self._last_step_t = t
        i = bucket_of(max(distance_bps(px, self._mid_at(t), self.side), 0.0), self.edges)
        q = float(self.calib.queue_base[i]) if self.calib is not None else self.queue0
        if np.isfinite(q) and q > 0:
            self.queue0 = q * self.queue_mult
        self.queue = self.queue0
        self.d0 = distance_bps(px, self._mid_at(t), self.side)
        self.n_requeues += 1


