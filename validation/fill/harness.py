def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Two-leg wave replay + n_slices A/B.")
    ap.add_argument("--data", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                    "data", "sample"))
    ap.add_argument("--symbols", default="")
    ap.add_argument("--slices", default="1,2,3,4")
    ap.add_argument("--seeds", default="0,1,2")
    ap.add_argument("--fill-mode", default="queue", choices=["queue", "price_through"])
    ap.add_argument("--okx-fill-mode", default="queue", choices=["queue", "price_through"])
    ap.add_argument("--signal-basis-bps", type=float, default=16.0)
    ap.add_argument("--pulse-every-s", type=float, default=120.0)
    ap.add_argument("--basis-tau-s", type=float, default=150.0)
    ap.add_argument("--clock-step-s", type=float, default=1.0)
    ap.add_argument("--entry-deadline-s", type=float, default=None)
    ap.add_argument("--queue-mult", type=float, default=1.0)
    ap.add_argument("--no-cancel", action="store_true")
    ap.add_argument("--synthetic", action="store_true",
                    help="use a fully synthetic Lighter leg too (no capture needed)")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "data", "ab_slices.json"))
    args = ap.parse_args(argv)

    slices = [int(x) for x in args.slices.split(",") if x.strip()]
    seeds = [int(x) for x in args.seeds.split(",") if x.strip()]
    common = dict(fill_mode=args.fill_mode, okx_fill_mode=args.okx_fill_mode,
                  signal_basis_bps=args.signal_basis_bps, pulse_every_s=args.pulse_every_s,
                  basis_tau_s=args.basis_tau_s, clock_step_s=args.clock_step_s,
                  entry_deadline_s=args.entry_deadline_s, queue_mult=args.queue_mult,
                  use_cancel=not args.no_cancel)

    if args.synthetic:
        caps = {"SYNTH": synthetic_capture(symbol="SYNTH", duration_s=1800.0, step_s=0.5,
                                           seed=17)}
    else:
        cap = load_capture(args.data)
        syms = [s.strip().upper() for s in args.symbols.split(",") if s.strip()] \
            or list(cap.symbols)
        caps = {s: cap for s in syms if s in cap.symbol_ids}
        if not caps:
            print(f"no symbols from {syms} in {args.data}", file=sys.stderr)
            return 2
        print(f"[harness] capture: {json.dumps(cap.describe(), indent=2)}")

    rows = []
    for sym, cap in caps.items():
        rows.extend(ab_slices(cap, sym, slices=slices, seeds=seeds, **common))
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump({"generated_utc": __import__("time").strftime("%Y-%m-%dT%H:%M:%SZ",
                                                                __import__("time").gmtime()),
                   "args": vars(args), "rows": rows}, fh, indent=2, default=str)
    print(f"{'sym':8}{'slices':>7}{'seed':>5}{'rounds':>7}{'paired':>7}{'abort':>7}"
          f"{'capfrac':>9}{'p_fail':>8}{'lag_p50':>9}{'requeue':>9}")
    for r in rows:
        print(f"{r['symbol']:8}{r['n_slices']:>7}{r['seed']:>5}{r['n_rounds']:>7}"
              f"{str(r['n_paired']):>7}{_f3(r['abort_rate']):>7}{_f3(r['capture_fraction_mean']):>9}"
              f"{_f3(r['p_fail']):>8}{_f3(r['pair_lag_median_s']):>9}{str(r['requeues']):>9}")
    print(f"[harness] wrote {args.out}")
    return 0


def _f3(x) -> str:
    return f"{x:.3f}" if isinstance(x, (int, float)) and x is not None and math.isfinite(x) else "-"


if __name__ == "__main__":
    raise SystemExit(main())
