@dataclass
class SimResult:
    rounds: list[RoundOutcome] = field(default_factory=list)
    fills: list[FillEvent] = field(default_factory=list)
    config: dict = field(default_factory=dict)
    timeline: dict = field(default_factory=dict)
    metrics: dict = field(default_factory=dict)
    counters: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {"config": self.config, "timeline": self.timeline, "counters": self.counters,
                "metrics": self.metrics,
                "rounds": [{"symbol": r.symbol, "round_id": r.round_id, "state": r.state,
                            "signal_ts": r.signal_ts, "signal_basis_bps": r.signal_basis_bps,
                            "first_fill_ts": r.first_fill_ts, "pair_ts": r.pair_ts,
                            "time_to_pair_s": r.time_to_pair_s, "naked_s": r.naked_s,
                            "realized_entry_basis_bps": r.realized_entry_basis_bps,
                            "aborted": r.aborted, "n_slices": r.n_slices,
                            "slices_filled": r.slices_filled, "source": r.source,
                            "notes": r.notes[-4:]} for r in self.rounds]}


def simulate_two_leg(
    lt_cap: Capture,
    symbol: str,
    *,
    qty_base: float = 1.0,
    ratio: float = 1.0,
    n_slices: int = 1,
    okx_cap: Optional[Capture] = None,
    okx_half_spread_bps: float = 1.0,
    okx_touch_size_base: float = 25.0,
    okx_trade_intensity_per_s: float = 1.5,
    okx_cancel_intensity_per_s: float = 0.5,
    signal_basis_bps: float = 16.0,
    pulse_every_s: float = 120.0,
    basis_tau_s: float = 150.0,
    basis_noise_bps: float = 0.8,
    params: Optional[WaveParams] = None,
    entry_deadline_s: Optional[float] = None,
    clock_step_s: float = 1.0,
    fill_mode: str = "queue",
    okx_fill_mode: str = "queue",
    queue_mult: float = 1.0,
    use_cancel: bool = True,
    seed: int = 0,
    minutes_to_close: float = float("inf"),
    passive_net_bps: float = 4.0,
    max_duration_s: Optional[float] = None,
    requote_keeps_queue: bool = True,
) -> SimResult:
    """Replay the wave state machine on two legs and measure what actually filled.

    Returns one ``RoundOutcome`` per (slice, triggered round).  ``n_slices>1``
    splits the order into ``n_slices`` independent rounds of ``qty/n_slices``
    quoting from the same signal, which is the "abort option" reading of slicing
    in `.field-guide/microstructure.md` (slicing buys optionality, not less impact).
    """
    p = params or WaveParams()
    if entry_deadline_s is not None:
        p = WaveParams(**{**p.__dict__, "entry_deadline_s": float(entry_deadline_s)})
    n_slices = max(1, int(n_slices))

    b = lt_cap.books(symbol)
    if not len(b["ts"]):
        raise ValueError(f"no Lighter book for {symbol} in capture (source={lt_cap.source})")
    t_start = float(b["ts"][0])
    t_end = float(b["ts"][-1])
    if max_duration_s:
        t_end = min(t_end, t_start + float(max_duration_s))
    grid = np.arange(t_start, t_end, clock_step_s)
    if len(grid) < 3:
        raise ValueError("capture too short for the requested clock step")

    basis = basis_path(grid, signal_basis_bps, pulse_every_s, basis_tau_s, basis_noise_bps, seed=seed)
    if okx_cap is None:
        okx_cap = okx_capture_from_basis(
            lt_cap, symbol, basis, grid, half_spread_bps=okx_half_spread_bps,
            touch_size_base=okx_touch_size_base,
            trade_intensity_per_s=okx_trade_intensity_per_s,
            cancel_intensity_per_s=okx_cancel_intensity_per_s, seed=seed + 101,
            step_s=min(clock_step_s, 0.5))
    okx_symbol = okx_cap.symbols[0]
    okx_source = okx_cap.source
    lt_source = lt_cap.source

    calibs = {}
    for venue, cap, sym in (("lighter", lt_cap, symbol), ("okx", okx_cap, okx_symbol)):
        for side in ("buy", "sell"):
            calibs[(venue, side)] = calibrate(cap, sym, side)

    mids = {"lighter": MidSeries.from_capture(lt_cap, symbol, "lighter"),
            "okx": MidSeries.from_capture(okx_cap, okx_symbol, "okx")}

    clock = FakeClock(t_start)
    rng = np.random.default_rng(seed)
    qty_slice = qty_base / n_slices
    rounds: list[Round] = []
    outcomes: list[RoundOutcome] = []
    fills_all: list[FillEvent] = []
    resting: dict[int, dict[str, RestingOrderSim]] = {i: {} for i in range(n_slices)}
    outcome_of: dict[int, RoundOutcome] = {}
    counters = {"quotes": 0, "requeues": 0, "kept_queue": 0, "cancels": 0, "ioc": 0,
                "fills_lighter": 0, "fills_okx": 0, "fill_reasons": {}}

    with patched_clock(clock):
        prev_t = t_start
        for t in grid:
            clock.set(float(t))
            lt_book = book_asof(lt_cap, symbol, "lighter", float(t))
            okx_book = book_asof(okx_cap, okx_symbol, "okx", float(t))
            if not lt_book.bids or not okx_book.bids:
                prev_t = float(t)
                continue
            basis_now = (lt_book.mid - okx_book.mid) / okx_book.mid * 1e4

            # ---- decide (real state machine) --------------------------------
            for i in range(n_slices):
                if i not in rounds:
                    rounds.append(Round(symbol=symbol, params=p, round_id=0, exit_state_ts=0.0))
                rnd = rounds[i]
                was_flat = rnd.state == RoundState.FLAT
                rid_before = rnd.round_id
                intents = wave.decide(rnd, basis_now, okx_book, lt_book, ratio, qty_slice,
                                      passive_net_bps, minutes_to_close)
                if was_flat and rnd.state != RoundState.FLAT:
                    oc = RoundOutcome(symbol=symbol, round_id=rnd.round_id, signal_ts=float(t),
                                      signal_basis_bps=float(basis_now), n_slices=n_slices,
                                      source=f"lighter={lt_source}/okx={okx_source}")
                    outcomes.append(oc)
                    outcome_of[i] = oc
                elif rnd.round_id != rid_before and i in outcome_of:
                    outcome_of[i] = next(o for o in reversed(outcomes)
                                         if o.round_id == rnd.round_id and o.symbol == symbol)

                # ---- apply intents -----------------------------------------
                for it in intents:
                    if it.kind == "quote" and it.order is not None:
                        o = it.order
                        key = o.venue
                        cur = resting[i].get(key)
                        if cur is not None and requote_keeps_queue and abs(cur.px - o.px) < 1e-12:
                            counters["kept_queue"] += 1
                            continue
                        if cur is not None:
                            cur.requeue(o.px, float(t))
                            counters["requeues"] += 1
                        else:
                            cap_v = lt_cap if key == "lighter" else okx_cap
                            sym_v = symbol if key == "lighter" else okx_symbol
                            counters["quotes"] += 1
                            resting[i][key] = RestingOrderSim(
                                cap_v, sym_v, key, o.side, o.px, o.qty_base, float(t),
                                calibs[(key, o.side)],
                                np.random.default_rng(seed + 1000 * i + hash((key, o.side)) % 997),
                                mode=fill_mode if key == "lighter" else okx_fill_mode,
                                queue_mult=queue_mult, use_cancel=use_cancel,
                                source=lt_source if key == "lighter" else okx_source)
                    elif it.kind == "cancel":
                        if it.venue == "all":
                            counters["cancels"] += len(resting[i])
                            resting[i].clear()
                        elif it.venue in resting[i]:
                            resting[i].pop(it.venue)
                            counters["cancels"] += 1
                    elif it.kind == "ioc" and it.order is not None:
                        counters["ioc"] += 1
                        o = it.order
                        wave.on_fill(rnd, o.venue, o.qty_base, o.px)
                        fills_all.append(FillEvent(venue=o.venue, symbol=symbol, side=o.side,
                                                   px=o.px, qty_base=o.qty_base, ts=float(t),
                                                   resting=False, slice_id=i,
                                                   source=lt_source if o.venue == "lighter" else okx_source))
                        resting[i].pop(o.venue, None)

            # ---- advance resting orders, push fills -------------------------
            for i in range(n_slices):
                rnd = rounds[i] if i < len(rounds) else None
                if rnd is None:
                    continue
                for venue, sim in list(resting[i].items()):
                    fts = sim.step(float(t))
                    if fts is None:
                        continue
                    counters[f"fills_{venue}"] = counters.get(f"fills_{venue}", 0) + 1
                    counters["fill_reasons"][sim.fill_reason] = \
                        counters["fill_reasons"].get(sim.fill_reason, 0) + 1
                    wave.on_fill(rnd, venue, sim.qty, sim.px)
                    fills_all.append(FillEvent(
                        venue=venue, symbol=symbol, side=sim.side, px=sim.px, qty_base=sim.qty,
                        ts=fts, distance_bps=sim.d0, resting=True, slice_id=i,
                        source=lt_source if venue == "lighter" else okx_source))
                    resting[i].pop(venue, None)

            # ---- bookkeeping for outcomes -----------------------------------
            for i in range(n_slices):
                if i >= len(rounds) or i not in outcome_of:
                    continue
                rnd, oc = rounds[i], outcome_of[i]
                if oc.state == rnd.state.value and rnd.state != RoundState.FLAT:
                    continue
                oc.state = rnd.state.value
                filled = [l for l in rnd.entry_legs if l.filled_qty > 0]
                if filled and not np.isfinite(oc.first_fill_ts):
                    oc.first_fill_ts = float(t)
                    oc.fills = [f for f in fills_all if f.slice_id == i and f.resting is not None]
                if rnd.state == RoundState.HEDGED and not np.isfinite(oc.pair_ts):
                    oc.pair_ts = float(t)
                if rnd.state == RoundState.ABORT_UNWIND:
                    oc.aborted = True
                if rnd.state == RoundState.FLAT and (np.isfinite(oc.pair_ts) or oc.aborted):
                    oc.exit_ts = float(t)
                    lt_leg = next((l for l in rnd.entry_legs if l.venue == "lighter" and l.filled_qty > 0), None)
                    ox_leg = next((l for l in rnd.entry_legs if l.venue == "okx" and l.filled_qty > 0), None)
                    if lt_leg and ox_leg:
                        oc.realized_entry_basis_bps = (
                            (lt_leg.filled_px - ox_leg.filled_px) / ox_leg.filled_px * 1e4
                            if ox_leg.side == "buy"
                            else (ox_leg.filled_px - lt_leg.filled_px) / ox_leg.filled_px * 1e4)
                    oc.slices_filled = len(filled)
                    oc.notes = list(rnd.notes[-3:])
                    oc.fills = [f for f in fills_all if f.slice_id == i]
                    resting[i].clear()
                    outcome_of.pop(i, None)
                    rounds[i] = Round(symbol=symbol, params=p, round_id=rnd.round_id,
                                      exit_state_ts=0.0)
            prev_t = float(t)

    # ---- roll up -------------------------------------------------------------
    for oc in outcomes:
        if not np.isfinite(oc.first_fill_ts) and oc.fills:
            oc.first_fill_ts = min(f.ts for f in oc.fills)
        oc.fills = oc.fills or [f for f in fills_all if f.slice_id == 0]
    kept = [o for o in outcomes if np.isfinite(o.signal_ts)]
    deadlines = tuple(sorted({d for d in (30.0, 60.0, 120.0, 300.0, 600.0, 900.0, 1800.0,
                                          float(p.entry_deadline_s))
                              if d <= (t_end - t_start) * 1.05}))
    res = SimResult(rounds=kept, fills=fills_all, counters=counters,
                    config={
                        "symbol": symbol, "qty_base": qty_base, "ratio": ratio,
                        "n_slices": n_slices, "fill_mode": fill_mode,
                        "okx_fill_mode": okx_fill_mode, "queue_mult": queue_mult,
                        "use_cancel": use_cancel, "clock_step_s": clock_step_s,
                        "signal_basis_bps": signal_basis_bps, "pulse_every_s": pulse_every_s,
                        "basis_tau_s": basis_tau_s, "basis_noise_bps": basis_noise_bps,
                        "entry_deadline_s": p.entry_deadline_s, "exit_bps": p.exit_bps,
                        "entry_bps": p.entry_bps, "seed": seed,
                        "lighter_source": lt_source, "okx_source": okx_source,
                        "requote_keeps_queue": requote_keeps_queue,
                    },
                    timeline={"t_start": t_start, "t_end": t_end,
                              "duration_s": round(t_end - t_start, 1), "steps": int(len(grid)),
                              "lt_book_msgs": int(len(b["ts"])),
                              "measurable_deadlines_s": list(deadlines)},
                    metrics={})
    res.metrics = {
        "summary": summarize(kept, mids, p.entry_deadline_s),
        "p_fail_by_deadline": p_fail_curve(kept, deadlines) if deadlines else [],
        "capture_fraction": capture_fraction(kept),
        "time_to_pair": time_to_pair(kept),
        "calibration": {f"{v}:{s}": calibs[(v, s)].to_dict()
                        for (v, s) in calibs if v == "lighter"},
    }
    return res


def ab_slices(lt_cap: Capture, symbol: str, slices: Sequence[int] = (1, 2, 3, 4),
              seeds: Sequence[int] = (0, 1, 2), **kwargs) -> list[dict]:
    """A/B ``n_slices`` on identical basis paths (same seed => same opportunity set)."""
    rows = []
    for n in slices:
        for seed in seeds:
            r = simulate_two_leg(lt_cap, symbol, n_slices=n, seed=seed, **kwargs)
            cf = r.metrics["capture_fraction"]
            ttp = r.metrics["time_to_pair"]
            pf = p_fail(r.rounds, r.config["entry_deadline_s"])
            rows.append({"symbol": symbol, "n_slices": n, "seed": seed,
                         "source": r.config["lighter_source"] + "+" + r.config["okx_source"],
                         "n_rounds": len(r.rounds),
                         "n_paired": cf.get("n_paired"), "abort_rate": cf.get("abort_rate"),
                         "capture_fraction_mean": cf.get("capture_fraction_mean"),
                         "capture_fraction_weighted": cf.get("capture_fraction_weighted"),
                         "p_fail": pf.get("p_fail"), "p_fail_n": pf.get("n_first_filled"),
                         "pair_lag_median_s": ttp.get("pair_lag_p50_s"),
                         "naked_p90_s": (ttp.get("naked_leg_exposure_s") or {}).get("p90"),
                         "quotes": r.counters["quotes"], "requeues": r.counters["requeues"],
                         "kept_queue": r.counters["kept_queue"], "ioc": r.counters["ioc"],
                         "fill_reasons": r.counters["fill_reasons"],
                         "duration_s": r.timeline["duration_s"]})
    return rows


# --------------------------------------------------------------------------- #
# CLI: run the A/B on a capture directory
