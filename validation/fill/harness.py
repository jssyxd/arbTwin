"""Backtest hooks: drive `arbtwin.wave` against a recorded (or synthetic) capture.

``simulate_two_leg(...)`` is the entry point.  It is a *fake-clock* event replay:

* the **Lighter leg** uses the recorded book and trade tape, so its queue
  depletion, cancel flow and price-through events are measurements;
* the **OKX leg** is synthetic while OKX is unreachable from this host
  (`.field-guide/environment.md`, `PLAN.zh.md` §5).  Its mid is the Lighter mid
  minus a prescribed basis path, its queue/flow are generated by
  ``fill_model.synthetic_capture``.  Every fill from it carries
  ``source="synthetic"`` and is reported separately -- a synthetic leg can never
  be averaged into a captured number without saying so;
* the state machine is the real one (``arbtwin.wave.decide`` / ``on_fill``), with
  ``arbtwin.wave.time`` rebound to a fake clock, so nothing about the strategy
  logic is reimplemented here;
* fills come from ``RestingOrderSim``: a recorded strict move-through always
  fills (that is a fact), otherwise the queue drains stochastically at the rates
  measured by ``fill_model.calibrate``.

Re-pegging: ``wave.decide`` re-emits a post-only quote at the current touch on
every poll.  If the price is unchanged we *keep* the existing order and its queue
position (that is what a real post-only amend-at-same-price does); if it changed
we cancel/replace and the order goes to the back of the queue.  ``requeues`` is
reported because on a 0.01-tick book this is the difference between a fill and
never filling.
"""

